"""Writes docs/x4_report.md from results files only (numbers are never typed by hand).

Every results number carries a marker [r:<file>#<dotted.key>] that tools/check_claims.py
(M7) can rebuild from the JSON file. Standard library only.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.dirname(HERE)
ROOT = os.path.dirname(SIM)
H1F = "results/x4_h1.json"
REPRO = "sim/results/repro_table1.json"
TIMING = "sim/results/x4_timing.json"
MEMC = "sim/results/mem_check.json"


def load(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
        return json.load(fh)


def get(d, key):
    cur = d
    for part in key.split("."):
        cur = cur[int(part)] if isinstance(cur, list) else cur[part]
    return cur


def fmt(v, nd):
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int) and nd == 0:
        return str(v)
    return ("%." + str(nd) + "f") % v


def make_r(files):
    def r(rel, key, nd=1, pct=False):
        v = get(files[rel], key)
        if pct:
            return "%s%% [r:%s#%s]" % (fmt(100 * v, nd), rel, key)
        return "%s [r:%s#%s]" % (fmt(v, nd), rel, key)
    return r


def main():
    files = {H1F: load(H1F), REPRO: load(REPRO), TIMING: load(TIMING), MEMC: load(MEMC)}
    r = make_r(files)
    h = files[H1F]
    per = h["perRegimeAttack"]
    L = []
    w = L.append
    verdict = "holds" if h["H1"] else "does not hold"
    w("# X4: a budgeted exploration track on the TRACE simulator")
    w("")
    w("Pre-registered 2026-10-24 (nikunj/EXPERIMENTS.md, X4) and run unchanged, except FASTPLAN cut 4: only the partitioned regime ran. "
      "Generated by `sim/analysis/x4_report.py` from the results files; every number carries its source marker.")
    w("")
    w("## Result")
    w("")
    w("- **H1 %s.** H1 needed the frontier to move at B* = 5%% for at least 3 of 4 attacks in the partitioned regime; it moved for %s attacks. H1 = %s." % (
        verdict, r(H1F, "attacksMovedAtBstar", 0), r(H1F, "H1")))
    for i, p in enumerate(per):
        w("- %s: frontier moves at B* = %s; the EB(5%%) point beats every convex combination of the four baselines in %s of 1,000 seed-bootstrap resamples (95%% needed); point estimate moves = %s." % (
            p["attack"], r(H1F, "perRegimeAttack.%d.movesAtBstar" % i), r(H1F, "perRegimeAttack.%d.bootstrapFractionAtBstar" % i, 1, True),
            r(H1F, "perRegimeAttack.%d.pointEstimateMovesAtBstar" % i)))
    w("- Pitch consequence (IDEA section 11): %s" % (
        "the X4 frontier plot may be shown, labeled as a simulation result in sats." if h["H1"] else
        "lead with the hard bound only (loss to unproven payees <= explorationCap per window, X5) and show the curves as they are."))
    w("- Unit: %s." % h["unitCaveat"])
    w("")
    w("## Question")
    w("")
    w("TRACE (CIKM '26) section 7.1 leaves \"separate tracks with independent budgets\" as future work: greedy selection cuts fraud but serves fewer honest providers, and in the partitioned view (each buyer sees only its own 60 jobs) greedy is the riskier choice. "
      "X4 asks whether TRACE+EB(B), the budgeted exploration track the wallet enforces on-chain (D3), moves the fraud vs served-honest frontier beyond the paper's own policies.")
    w("")
    w("## What ran")
    w("")
    w("- **Fork.** Public Trace_CIKM @94c4b9f vendored in `sim/` with no vendored file modified; three missing modules stubbed as no-ops; every addition listed in `sim/patches.json`.")
    w("- **Repro gate (M6, X4 step 0).** TRACE-no-bandit, strategic-default, centralized Table 1 contract, seeds 42-51: mean fraud %s sats, sd %s, against the paper's %s +/- %s; pass = %s." % (
        r(REPRO, "mean", 1), r(REPRO, "sd", 2), r(REPRO, "paperMean", 1), r(REPRO, "band", 1), r(REPRO, "pass")))
    w("- **Regime.** Partitioned, the author's `_partitionedViewWorker` contract behind Table 9: 5 independent buyers, 60 jobs each (60 rounds x 1 job), N = 1,000 agents, 30% malicious, propagation delay 2. "
      "Each buyer session runs in its own process: the author's single-process worker carries module state from one buyer into the next, which contradicts the paper's \"no shared state between buyers\".")
    w("- **Policies.** TRACE+EB(B) for B in {0, 1, 2, 5, 10}%%, plus the baselines TRACE-full, TRACE-no-bandit, REPUTATION and EigenTrust rerun in the same fork and seeds. Attacks: strategic-default, collusion-ring, sybil-cluster, game-theoretic (p75). Seeds 42-51. Cells: %s." % r(H1F, "nCells", 0))
    w("- **TRACE+EB(B)** (`sim/hx/ebPolicy.ts`): per job, if exploration spend + price <= B x total spend (this job included), pick by TRACE's Thompson-sampling selection among eligible unproven, non-flagged providers; otherwise pick by TRACE-no-bandit's greedy selection among proven providers, or among all non-flagged ones while none is proven. Flagged providers are never picked. "
      "Tier rule (`sim/hx/tierRule.ts`): flagged = the router's existing Sybil filters fire; proven = not flagged and the 95% LCB under Beta(1,3) is at least that of 3 successes and 0 failures; everything else is unproven.")
    w("- **Metrics.** Fraud = %s. Served-honest = %s. Malicious-routing rate MR = share of jobs routed to malicious providers." % (h["metrics"]["fraud"], h["metrics"]["servedHonest"]))
    w("- **Test.** For each attack, the 10-seed mean points of the four baselines span a convex hull. EB(B) moves the frontier iff no convex combination has fraud <= and served-honest >= the EB point (exact LP via the 2-D segment test, cross-checked on a simplex grid), in >= 95%% of 1,000 paired seed-bootstrap resamples (RNG seed %s)." % h["bootstrap"]["rngSeed"])
    w("")
    w("## Results by attack (10-seed means)")
    w("")
    for i, p in enumerate(per):
        w("### %s" % p["attack"])
        w("")
        w("| Policy | Fraud (sats) | Served honest | MR | Bootstrap share beating the hull | Moves |")
        w("|---|---|---|---|---|---|")
        for b in h["baselines"]:
            base = "perRegimeAttack.%d.baselines.%s" % (i, b)
            w("| %s | %s | %s | %s | | |" % (b, r(H1F, base + ".fraud"), r(H1F, base + ".servedHonest"), r(H1F, base + ".mr", 1, True)))
        for bv in h["sweepB"]:
            k = "perRegimeAttack.%d.sweep.%d" % (i, bv)
            star = " (B*)" if bv == h["Bstar"] else ""
            w("| TRACE+EB(%d%%)%s | %s | %s | %s | %s | %s |" % (
                bv, star, r(H1F, k + ".fraud"), r(H1F, k + ".servedHonest"), r(H1F, k + ".mr", 1, True),
                r(H1F, k + ".bootstrapFraction", 1, True), r(H1F, k + ".moves")))
        w("")
        w("Plot: `sim/results/x4_frontier_partitioned_%s.png`." % p["attack"])
        w("")
    w("All B values are reported; B* = 5% was fixed before the runs (the wallet default) and none was picked afterwards.")
    w("")
    w("## Reading the result")
    w("")
    for i, p in enumerate(per):
        dom = p["dominatedOutrightByAtBstar"]
        w("- %s: EB(5%%) puts %s of its spend into the exploration track; its point is %s." % (
            p["attack"], r(H1F, "perRegimeAttack.%d.exploreSpendShareAtBstar" % i, 1, True),
            ("dominated outright by " + ", ".join(dom)) if dom else "not dominated by any single baseline, only by a mix of two"))
    w("- The budget binds as designed (the exploration share sits just under B), so EB(B) is a bounded track. Its points still fall inside the baselines' hull on every attack: in the partitioned view the baselines that serve the most honest providers do so at comparable or lower fraud. "
      "That is consistent with the paper's section 7.3 observation that with thin local evidence exploration is insurance rather than waste; restricting the non-exploration track to proven payees costs openness here without buying lower fraud.")
    w("")
    w("## Sanity check against the paper (not a gate)")
    w("")
    w("Partitioned fraud, ours (10 seeds, one process per buyer) vs the paper's Table 9 (5 seeds, single-process worker):")
    w("")
    w("| Policy | strategic-default | collusion-ring | sybil-cluster | game-theoretic |")
    w("|---|---|---|---|---|")
    for b in h["baselines"]:
        cells = []
        for a in ["strategic-default", "collusion-ring", "sybil-cluster", "game-theoretic"]:
            cells.append("%s vs %s" % (r(H1F, "sanity.fraud.%s.%s.ours" % (b, a)), r(H1F, "sanity.fraud.%s.%s.paperTable9" % (b, a))))
        w("| %s | %s |" % (b, " | ".join(cells)))
    w("")
    w("## Engineering notes")
    w("")
    w("- **DB backend.** A CPU profile put most simulation time in the Prisma 7 runtime, so the sweep runs on an in-memory implementation of the Prisma subset the simulator uses (`sim/hx/memPrisma.ts`), installed through the `globalThis.prisma` hook `src/lib/db.ts` already has. "
      "Gate (`sim/hx/memCheck.ts`): %s of %s deterministic Prisma+SQLite session units reproduce bit for bit (job-sequence hashes, all four attacks), and %s of %s repro cells give identical fraud, served-honest and MR; gate pass = %s. "
      "REPUTATION is the exception by construction: its seeded jitter stream is also drawn by Prisma's id generator, so all REPUTATION cells use the memory backend." % (
          r(MEMC, "deterministicUnitsIdentical", 0), r(MEMC, "deterministicUnitsCompared", 0), r(MEMC, "reproCellsIdentical", 0), r(MEMC, "reproCellsCompared", 0), r(MEMC, "pass")))
    t = files[TIMING]
    if "partitionedSweep" in t and "byBackend" in t["partitionedSweep"]:
        w("- **Runtime.** %s session units: %s on the memory backend at a mean of %s s and %s GB each, %s on Prisma+SQLite at %s s and %s GB each; the final run took %s s at up to %s parallel units (`sim/results/x4_timing.json`)." % (
            r(TIMING, "partitionedSweep.sessionUnits", 0),
            r(TIMING, "partitionedSweep.byBackend.memory.units", 0), r(TIMING, "partitionedSweep.byBackend.memory.meanSec", 1), r(TIMING, "partitionedSweep.byBackend.memory.meanRssGB", 2),
            r(TIMING, "partitionedSweep.byBackend.prisma-sqlite.units", 0), r(TIMING, "partitionedSweep.byBackend.prisma-sqlite.meanSec", 1), r(TIMING, "partitionedSweep.byBackend.prisma-sqlite.meanRssGB", 2),
            r(TIMING, "partitionedSweep.lastRun.wallClockSec", 0), r(TIMING, "partitionedSweep.lastRun.maxObservedConcurrent", 0)))
    w("- **Determinism.** The vendored REPUTATION/PRICE utilities draw unseeded `Math.random()` jitter; the worker seeds it per buyer session, so every cell reproduces from its seed.")
    w("- **Implementation choices** fixed before the scored runs are logged in `DECISIONS.md` ([SIM] lines).")
    w("")
    w("## Limits")
    w("")
    w("- Simulated market, fixed-script adversaries and binary outcomes, as in the paper; the sparse-centralized regime was cut.")
    w("- Served-honest sums distinct providers over 5 independently drawn buyer markets, so its scale differs from the paper's centralized Table 8 (x/700).")
    w("- X4 informs the wallet's default B; the wallet's own guarantee is the hard per-window cap (X5), which does not depend on this result.")
    w("")
    w("## Reproduce")
    w("")
    w("```")
    w("npm --prefix sim install")
    w("npm --prefix sim run repro      # M6 gate -> sim/results/repro_table1.json")
    w("npm --prefix sim run x4         # resumable sweep -> sim/results/x4_cells.jsonl")
    w("uv run python sim/analysis/x4_analyze.py && python sim/analysis/x4_report.py")
    w("```")
    w("")
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "x4_report.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    print("wrote docs/x4_report.md")


if __name__ == "__main__":
    main()
