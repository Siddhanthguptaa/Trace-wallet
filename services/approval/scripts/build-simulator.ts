/**
 * Regenerate src/simulatorArtifact.ts from contracts/ApprovalSimulator.sol (solc 0.8.28, cancun,
 * optimizer 200). test/anvil.test.ts recompiles and fails if the checked-in runtime drifts.
 *   pnpm --filter @hypnexis/approval build:sim
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SIMULATOR_SOURCE, SVC_ROOT, compile, findSolc } from './lib/devchain.ts';

const solc = findSolc();
if (!solc) throw new Error('solc 0.8.28 not found (set SOLC)');
const art = compile(solc, [SIMULATOR_SOURCE]).ApprovalSimulator;
if (!art) throw new Error('ApprovalSimulator missing from solc output');
const fn = (art.abi as readonly { type: string; name?: string }[]).filter((x) => x.type === 'function' && x.name === 'simulate');
const body = `/**
 * GENERATED by scripts/build-simulator.ts from contracts/ApprovalSimulator.sol. Do not edit.
 * Runtime code placed at the account address by an eth_call state override (src/simulate.ts).
 */
export const SIMULATOR_RUNTIME = '${art.runtime}' as const;

export const simulatorAbi = ${JSON.stringify(fn, null, 2)} as const;
`;
writeFileSync(join(SVC_ROOT, 'src', 'simulatorArtifact.ts'), body);
console.log(`simulator runtime ${(art.runtime.length - 2) / 2} bytes -> src/simulatorArtifact.ts`);
