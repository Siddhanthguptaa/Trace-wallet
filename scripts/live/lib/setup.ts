/**
 * `live.ts init | deploy | fund | fund-keys`.
 *
 * init     writes `.env.live` (throwaway testnet keys + the owner's PUBLIC address) and `web/.env`.
 * deploy   puts the real stack on the chain from the forge artifacts (libraries linked) and creates the
 *          FOUR demo wallets the runner attacks, all holding the same asset (real test USDC):
 *            R1 the agent's own EOA (no policy)           R2 NaiveAccount: static allowlist + caps
 *            R3 AgentAccount, no payee tiers (owner = YOUR MetaMask, configured in the frontend)
 *            R4 AgentAccount with payee tiers + the real attestor (owner = YOUR MetaMask)
 * fund     prints exactly what to send where, and (--send) distributes faucet USDC from the deployer.
 * The owner key is never generated, read or stored.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { type Address, type Hex, formatEther, formatUnits, getAddress, isAddress, parseEther, toFunctionSelector } from 'viem';
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts';
import { artifactsDir, createAccount, deployStack, loadArtifact } from '../../lib/stack.ts';
import { CHAINS, ENTRYPOINT_V08, chainByKey, txUrl } from './chains.ts';
import { makeDeployer, publicClient, sleep, stackOf, usdcAbi, walletClient } from './chainio.ts';
import { ENV_EXAMPLE, ENV_LIVE, ROOT, WEB_ENV, type Live, guardMainnet, readLive, renderEnv, updateEnv } from './envfile.ts';

export interface InitOptions {
  owner?: string;
  chain: string;
  rpc?: string;
  merchant?: string;
  force: boolean;
  allowMainnet: boolean;
  usdc?: string;
  log: (m: string) => void;
}

async function rpcChainId(rpc: string): Promise<number> {
  const res = await fetch(rpc, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'eth_chainId', params: [] }), signal: AbortSignal.timeout(8000) });
  return Number(BigInt(((await res.json()) as { result: string }).result));
}

/** web/.env: the frontend reads ONE gateway URL for all four backends (VITE_*). Never holds a key. */
export function writeWebEnv(L: Live): void {
  const g = L.urls.gateway;
  const lines = [
    '# Generated by `live.ts init|deploy` (git-ignored). Edit .env.live, not this file. No secret is ever written here.',
    `VITE_APPROVAL_URL=${g}`,
    `VITE_ATTESTOR_URL=${g}`,
    `VITE_AGENT_TOOLS_URL=${g}`,
    `VITE_RUNNER_URL=${g}`,
    `VITE_CHAIN_ID=${L.chainId}`,
    `VITE_RPC_URL=${L.rpcUrl}`,
    `VITE_WALLET_ADDRESS=${L.wallets.R4 || L.account || ''}`,
    `VITE_FACTORY_ADDRESS=${L.factory || ''}`,
    `VITE_ENTRYPOINT_ADDRESS=${L.entryPoint}`,
    // Prefill for the console's Setup form (public addresses and demo numbers only; no secret)
    `VITE_SALT=${L.salt}`,
    `VITE_USDC_ADDRESS=${L.usdc}`,
    `VITE_AGENT_ADDRESS=${L.addr.agent}`,
    `VITE_ATTESTOR_ADDRESS=${L.addr.attestor}`,
    `VITE_WATCHER_ADDRESS=${L.addr.watcher}`,
    `VITE_MERCHANT_ADDRESS=${L.merchant || ''}`,
    `VITE_DAILY_USDC=${formatUnits(L.policy.burst + L.policy.rate, 6)}`,
    `VITE_FUND_USDC=${formatUnits(L.fundUsdc ?? 3_000_000n, 6)}`,
    '',
  ];
  mkdirSync(join(WEB_ENV, '..'), { recursive: true });
  writeFileSync(WEB_ENV, lines.join('\n'));
}

export async function init(o: InitOptions): Promise<void> {
  const info = chainByKey(o.chain);
  if (info.mainnet && !o.allowMainnet) throw new Error(`${info.name} is a MAINNET: refused. Pass --allow-mainnet (the contracts are UNAUDITED; keep at most ~1 USDC in the account).`);
  if (o.owner && /^0x[0-9a-fA-F]{64}$/.test(o.owner)) throw new Error('that looks like a PRIVATE KEY. Stop: the owner key must stay in MetaMask. Pass the public address.');
  if (o.owner && !isAddress(o.owner)) throw new Error('--owner must be your MetaMask ACCOUNT ADDRESS (0x…, 42 characters), never a private key or a seed phrase');
  const log = o.log;

  if (existsSync(ENV_LIVE) && !o.force) {
    if (o.owner) {
      updateEnv({ OWNER_ADDRESS: getAddress(o.owner) });
      log(`.env.live already exists: OWNER_ADDRESS updated to ${getAddress(o.owner)} (keys kept; pass --force to regenerate everything)`);
    } else log('.env.live already exists (keys kept). Pass --force to regenerate everything, or --owner 0x… to change the owner.');
    const L = readLive();
    writeWebEnv(L);
    printNext(L, log);
    return;
  }
  if (!o.owner) throw new Error('--owner 0x<your MetaMask address> is required for the first init');

  const rpc = o.rpc ?? info.rpc;
  const chainId = await rpcChainId(rpc).catch((e) => {
    throw new Error(`cannot reach ${rpc}: ${(e as Error).message}`);
  });
  if (chainId !== info.chainId) throw new Error(`${rpc} reports chain ${chainId}, expected ${info.chainId} (${info.name})`);

  const key = () => generatePrivateKey();
  const guardianKeys = Array.from({ length: 5 }, key);
  const merchant = o.merchant ? getAddress(o.merchant) : privateKeyToAccount(key()).address; // key discarded: a plain receiving address
  const usdc = o.usdc ? getAddress(o.usdc) : info.usdc;
  if (!usdc) throw new Error(`no USDC address known for ${info.key}: pass --usdc 0x…`);
  const values: Record<string, string> = {
    CHAIN: info.key,
    CHAIN_ID: String(info.chainId),
    RPC_URL: rpc,
    EXPLORER_URL: info.explorer,
    ENTRYPOINT: ENTRYPOINT_V08,
    USDC: usdc,
    OWNER_ADDRESS: getAddress(o.owner),
    DEPLOYER_KEY: key(),
    AGENT_KEY: key(),
    ATTESTOR_KEY: key(),
    WATCHER_KEY: key(),
    ATTACKER_KEY: key(),
    VERIFIER_KEY: key(),
    GUARDIAN_ADDRESSES: guardianKeys.map((k) => privateKeyToAccount(k).address).join(','),
    GUARDIAN_KEYS: guardianKeys.join(','),
    MERCHANT_ADDRESS: merchant,
  };
  writeFileSync(ENV_LIVE, renderEnv(readFileSync(ENV_EXAMPLE, 'utf8'), values));
  log(`wrote ${ENV_LIVE} (git-ignored; throwaway TESTNET keys; your owner key is NOT in it)`);

  const L = readLive();
  writeWebEnv(L);
  log(`wrote ${WEB_ENV} (git-ignored; frontend env, no secrets; all four backend URLs -> the gateway ${L.urls.gateway})`);
  const pub = publicClient(L);
  const ep = await pub.getCode({ address: L.entryPoint });
  log(`EntryPoint v0.8 at ${L.entryPoint}: ${ep && ep !== '0x' ? 'present (real, canonical)' : 'ABSENT on this chain: `deploy` will deploy the official eth-infinitism EntryPoint v0.8 artifact'}`);
  const uc = await pub.getCode({ address: L.usdc });
  if (!uc || uc === '0x') log(`WARNING: no contract at USDC ${L.usdc} on this chain`);
  else {
    const auth = await pub.readContract({ address: L.usdc, abi: usdcAbi, functionName: 'authorizationState', args: [L.addr.deployer, `0x${'00'.repeat(32)}`] }).then(() => 'supports EIP-3009 (authorizationState answers)', () => 'does NOT answer authorizationState');
    log(`USDC at ${L.usdc}: contract present, ${auth}`);
  }
  printNext(L, log);
}

export function printNext(L: Live, log: (m: string) => void): void {
  const info = CHAINS[L.chainKey]!;
  log('');
  log('NEXT 1: send the deployer / relayer a little test ETH (it pays for the deploy and relays every UserOp):');
  log(`  deployer / relayer   ${L.addr.deployer}   0.03 ETH`);
  for (const f of info.faucets.filter((x) => /ETH/.test(x.what))) log(`    ${f.what}: ${f.url}`);
  log(`  owner (your MetaMask) ${L.owner}   0.01 ETH for its own transactions (same faucets)`);
  log('NEXT 2: pnpm exec tsx scripts/live/live.ts deploy');
}

// ---------------------------------------------------------------- deploy

export interface DeployOptions {
  redeploy: boolean;
  allowMainnet: boolean;
  log: (m: string) => void;
}

const R2_SELECTORS = [toFunctionSelector('transfer(address,uint256)'), toFunctionSelector('approve(address,uint256)')];

export async function deploy(L: Live, o: DeployOptions): Promise<void> {
  guardMainnet(L, o.allowMainnet);
  const log = o.log;
  if (!L.owner) throw new Error('OWNER_ADDRESS is empty in .env.live: run `live.ts init --owner 0x…`');
  const pub = publicClient(L);
  const bal = await pub.getBalance({ address: L.addr.deployer });
  log(`deployer ${L.addr.deployer} holds ${formatEther(bal)} ETH`);
  const info = chainByKey(L.chainKey);
  if (L.factory && !o.redeploy) {
    log(`stack already deployed: factory ${L.factory} (pass --redeploy to deploy a new stack and new wallets)`);
  } else {
    if (bal < parseEther(process.env.MIN_DEPLOYER_ETH ?? '0.0006') && L.chainId !== 31337) throw new Error(`the deployer needs ~0.0007 ETH (0.006 gwei gas) to deploy the stack and four wallets (it has ${formatEther(bal)}): send test ETH to ${L.addr.deployer}`);
    log(`artifacts: ${artifactsDir()}`);
    const d = makeDeployer(L);
    let entryPoint: Address | undefined;
    const code = await pub.getCode({ address: L.entryPoint });
    if (code && code !== '0x') entryPoint = L.entryPoint;
    else {
      log('EntryPoint v0.8 absent: deploying the official EntryPoint v0.8 artifact (eth-infinitism)');
      entryPoint = await d.deploy(loadArtifact('EntryPoint'));
      updateEnv({ ENTRYPOINT: entryPoint });
      log(`  EntryPoint deployed at ${entryPoint}`);
    }
    log('deploying libraries, AgentAccountAdmin, AgentAccount implementation, factory, PolicyLens (a few minutes on a public RPC)...');
    const stack = await deployStack(d, { entryPoint, paymaster: false });
    updateEnv({ FACTORY: stack.factory, IMPLEMENTATION: stack.implementation, ADMIN: stack.admin, LENS: stack.lens, R1_ADDRESS: '', R2_ADDRESS: '', R3_ADDRESS: '', R4_ADDRESS: '', ACCOUNT: '' });
    for (const [n, a] of Object.entries({ factory: stack.factory, implementation: stack.implementation, admin: stack.admin, lens: stack.lens, ...stack.libs })) {
      log(`  ${n.padEnd(15)} ${a}${L.explorer ? `  ${L.explorer}/address/${a}` : ''}`);
    }
    mkdirSync(join(ROOT, 'deployments'), { recursive: true });
    writeFileSync(
      join(ROOT, 'deployments', `${L.chainId}.json`),
      `${JSON.stringify({ chainId: L.chainId, chain: L.chainKey, deployer: L.addr.deployer, entryPoint: stack.entryPoint, entryPointDeployedByUs: !(code && code !== '0x'), libraries: stack.libs, admin: stack.admin, implementation: stack.implementation, factory: stack.factory, lens: stack.lens, artifacts: artifactsDir().replace(ROOT, '.').split('\\').join('/'), deployedAt: new Date().toISOString() }, null, 2)}\n`,
    );
  }
  void info;
  await createWallets(readLive(), log);
}

/** R1..R4 (idempotent): each is created / configured only if it is not there yet. */
async function createWallets(L: Live, log: (m: string) => void): Promise<void> {
  const pub = publicClient(L);
  const d = makeDeployer(L);
  const stack = stackOf(L);
  const hasCode = async (a: Address | '') => (a ? ((await pub.getCode({ address: a })) ?? '0x') !== '0x' : false);
  const ex = (a: string) => (L.explorer ? `  ${L.explorer}/address/${a}` : '');

  // R1: the agent's own key, no policy. It needs a little ETH of its own to send plain transactions.
  const r1 = L.addr.agent;
  const r1Eth = await pub.getBalance({ address: r1 });
  if (r1Eth < parseEther('0.00004')) {
    const w = walletClient(L, L.deployerKey);
    const h = await w.sendTransaction({ to: r1, value: parseEther('0.00006') });
    await pub.waitForTransactionReceipt({ hash: h });
    log(`  R1 agent EOA: sent 0.001 ETH for its own gas  ${txUrl(L.explorer, h)}`);
  }
  log(`  R1 the agent's own EOA (no policy)           ${r1}${ex(r1)}`);

  // R3 / R4: factory clones owned by the MetaMask address. createAccount needs NO owner key.
  const make = async (label: string, salt: bigint): Promise<Address> => {
    const addr = getAddress(await d.read<Address>(L.factory as Address, stack.abi.factory, 'getAddress', [L.owner as Address, salt]));
    if (!(await hasCode(addr))) {
      const created = await createAccount(d, stack, L.owner as Address, salt);
      log(`  ${label} created ${created}`);
    }
    return addr;
  };
  const r3 = await make('R3', L.r3Salt);
  const r4 = await make('R4', L.salt);
  log(`  R3 ours, no payee tiers (owner = you)         ${r3}${ex(r3)}`);
  log(`  R4 ours, payee tiers + attestor (owner = you) ${r4}${ex(r4)}`);

  // R2: NaiveAccount, owned by the throwaway deployer: static (target, selector) allowlist, static recipients,
  // per-tx cap, calendar-day cap; isValidSignature accepts the agent key. The baseline most teams build.
  let r2 = L.wallets.R2;
  if (!r2 || !(await hasCode(r2))) {
    const art = loadArtifact('NaiveAccount', 'NaiveAccount.sol');
    r2 = await d.deploy(art, [L.addr.deployer, L.addr.agent]);
    const daily = L.policy.burst + L.policy.rate;
    await d.send(r2, art.abi, 'configure', [L.entryPoint, { targets: [L.usdc, L.usdc], selectors: R2_SELECTORS, recipients: [L.merchant], tokens: [L.usdc], perTxCaps: [L.policy.perTx], dailyCaps: [daily] }]);
    log(`  R2 deployed + configured (allowlist: USDC transfer/approve; recipients: merchant)`);
  }
  log(`  R2 static allowlist + caps (owner = deployer) ${r2}${ex(r2)}`);

  // EntryPoint deposits so R2/R3/R4 can pay UserOp gas (the deployer tops them up; anyone can depositTo).
  for (const [n, a] of [['R2', r2], ['R3', r3], ['R4', r4]] as const) {
    const dep = (await d.read<bigint>(L.entryPoint, stack.abi.entryPoint, 'balanceOf', [a])) as bigint;
    // R2 has no freeze, so every attack run mines the most ops there: it gets 3x the deposit of R3/R4.
    const want = n === 'R2' ? L.policy.depositWei * 3n : L.policy.depositWei;
    if (dep < want / 2n) {
      await d.send(L.entryPoint, stack.abi.entryPoint, 'depositTo', [a], L.deployerKey, want);
      log(`  ${n}: EntryPoint gas deposit +${formatEther(want)} ETH`);
    }
  }

  // gas money for the watcher and attestor keys (the real services send freeze / flag transactions)
  await fundKeys(L, { guardians: false, allowMainnet: true, log });
  updateEnv({ R1_ADDRESS: r1, R2_ADDRESS: r2, R3_ADDRESS: r3, R4_ADDRESS: r4, ACCOUNT: r4 });
  const live = { wallets: { R1: { address: r1, kind: 'eoa' }, R2: { address: r2, kind: 'naive' }, R3: { address: r3, kind: 'agent' }, R4: { address: r4, kind: 'agent' } }, R1: r1, R2: r2, R3: r3, R4: r4, factory: L.factory, lens: L.lens, usdc: L.usdc, entryPoint: L.entryPoint, agentAddress: L.addr.agent, relayer: L.addr.deployer, owner: L.owner, merchant: L.merchant, attestor: L.addr.attestor, watcher: L.addr.watcher, attacker: L.addr.attacker };
  const file = join(ROOT, 'deployments', `${L.chainId}.json`);
  const dep = existsSync(file) ? (JSON.parse(readFileSync(file, 'utf8')) as Record<string, unknown>) : {};
  writeFileSync(file, `${JSON.stringify({ ...dep, live }, null, 2)}\n`);
  const L2 = readLive();
  writeWebEnv(L2);
  log('');
  log(`wrote deployments/${L.chainId}.json (with a "live" section) and refreshed .env.live and web/.env`);
  log('');
  log('NEXT 3: fund the wallets with REAL test USDC:  pnpm exec tsx scripts/live/live.ts fund');
  log('NEXT 4: start the services:                    pnpm exec tsx scripts/live/live.ts services up');
  log('NEXT 5: owner setup of R3 and R4 in the frontend (or the owner tx pack):  pnpm exec tsx scripts/live/live.ts owner-pack');
}

// ---------------------------------------------------------------- fund

export async function fund(L: Live, o: { send: boolean; includeR4: boolean; allowMainnet: boolean; log: (m: string) => void }): Promise<void> {
  guardMainnet(L, o.allowMainnet);
  const log = o.log;
  const info = CHAINS[L.chainKey]!;
  const pub = publicClient(L);
  const dec = L.usdcDecimals;
  const usdcOf = (a: string) => pub.readContract({ address: L.usdc, abi: usdcAbi, functionName: 'balanceOf', args: [a as Address] }) as Promise<bigint>;
  const names = ['R1', 'R2', 'R3', 'R4'] as const;
  const bal: Record<string, bigint> = {};
  for (const n of names) bal[n] = L.wallets[n] ? await usdcOf(L.wallets[n]) : 0n;
  const dUsdc = await usdcOf(L.addr.deployer);
  const dEth = await pub.getBalance({ address: L.addr.deployer });
  const each = L.fundUsdc;
  const fmt = (x: bigint) => `${formatUnits(x, dec)} USDC`;
  log('');
  log(`Each of the four wallets should hold ${fmt(each)} of real test USDC (the same, so the attacks are comparable).`);
  log(`Total ${fmt(each * 4n)}: two Circle faucet requests (10 USDC each, the rest stays in your MetaMask / deployer).`);
  log('');
  for (const n of names) log(`  ${n}  ${L.wallets[n] || '(not deployed: run deploy)'}   holds ${fmt(bal[n]!)}   target ${fmt(each)}`);
  log(`  deployer  ${L.addr.deployer}   holds ${fmt(dUsdc)} and ${formatEther(dEth)} ETH`);
  log('');
  const usdcFaucet = info.faucets.find((f) => /USDC/.test(f.what));
  log('WHAT TO SEND (all real Base Sepolia test tokens):');
  log(`  1. ETH   0.03 -> deployer ${L.addr.deployer}   (deploy + relaying)`);
  log(`  2. ETH   0.01 -> your MetaMask ${L.owner}   (your own transactions)`);
  log(`  3. USDC  10   -> your MetaMask ${L.owner}   ${usdcFaucet ? usdcFaucet.url : ''}  (choose Base Sepolia). R4 is funded FROM METAMASK in the frontend (Setup, step 4): send ${fmt(each)} to R4.`);
  log(`  4. USDC  10   -> deployer ${L.addr.deployer}   (same faucet, second request). \`fund --send\` then pays R1, R2 and R3 ${fmt(each)} each from it.`);
  for (const f of info.faucets.filter((x) => /ETH/.test(x.what))) log(`     ETH faucet: ${f.url}`);
  if (!o.send) {
    log('');
    log('When the deployer holds the faucet USDC:  pnpm exec tsx scripts/live/live.ts fund --send');
    return;
  }
  const targets = (o.includeR4 ? names : (['R1', 'R2', 'R3'] as const)).filter((n) => L.wallets[n]);
  const w = walletClient(L, L.deployerKey);
  let left = dUsdc;
  for (const n of targets) {
    const need = each > bal[n]! ? each - bal[n]! : 0n;
    if (need === 0n) {
      log(`  ${n}: already holds ${fmt(bal[n]!)}`);
      continue;
    }
    if (left < need) {
      log(`  ${n}: needs ${fmt(need)} but the deployer only has ${fmt(left)} left: get more from the faucet and re-run`);
      continue;
    }
    const h = await w.writeContract({ address: L.usdc, abi: usdcAbi, functionName: 'transfer', args: [L.wallets[n] as Address, need] });
    await pub.waitForTransactionReceipt({ hash: h });
    left -= need;
    log(`  ${n}: sent ${fmt(need)}  ${txUrl(L.explorer, h)}`);
    await sleep(300);
  }
}

// ---------------------------------------------------------------- fund-keys

export async function fundKeys(L: Live, o: { eth?: string; guardians: boolean; allowMainnet: boolean; log: (m: string) => void }): Promise<void> {
  guardMainnet(L, o.allowMainnet);
  const pub = publicClient(L);
  const targets: { name: string; to: Address; eth: bigint }[] = [
    { name: 'watcher (freeze txs)', to: L.addr.watcher, eth: parseEther(o.eth ?? '0.00003') },
    { name: 'attestor (flag txs)', to: L.addr.attestor, eth: parseEther(o.eth ?? '0.00003') },
  ];
  if (o.guardians) for (const [i, g] of L.guardianAddresses.entries()) targets.push({ name: `guardian ${i + 1}`, to: g, eth: parseEther('0.0005') });
  const w = walletClient(L, L.deployerKey);
  for (const t of targets) {
    const have = await pub.getBalance({ address: t.to });
    if (have >= t.eth / 2n) {
      o.log(`  ${t.name}: already holds ${formatEther(have)} ETH`);
      continue;
    }
    const hash = await w.sendTransaction({ to: t.to, value: t.eth });
    await pub.waitForTransactionReceipt({ hash });
    o.log(`  ${t.name}: sent ${formatEther(t.eth)} ETH to ${t.to}  ${txUrl(L.explorer, hash)}`);
    await sleep(300);
  }
}

